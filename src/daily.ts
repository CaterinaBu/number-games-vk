const DIFFICULTIES: Record<DailyDifficulty, {
  label: string;
  reward: number;
  thresholds: Record<DailyGame, number>;
}> = {
  easy: {
    label: 'Лёгкое',
    reward: 20,
    thresholds: { compare: 6, guess: 50, order: 4, near: 6 }
  },
  medium: {
    label: 'Среднее',
    reward: 30,
    thresholds: { compare: 7, guess: 60, order: 5, near: 7 }
  },
  hard: {
    label: 'Сложное',
    reward: 40,
    thresholds: { compare: 8, guess: 70, order: 6, near: 8 }
  }
};

function hashString(value: string): number {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function seededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state += 0x6D2B79F5;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function getMoscowDateKey(date = new Date()): string {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/Moscow',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit'
  }).formatToParts(date);

  const year = parts.find((part) => part.type === 'year')?.value ?? '1970';
  const month = parts.find((part) => part.type === 'month')?.value ?? '01';
  const day = parts.find((part) => part.type === 'day')?.value ?? '01';
  return `${year}-${month}-${day}`;
}

function flattenStories() {
  const stories: Array<{
    storyId: string;
    location: DailyLocation;
    game: DailyGame;
    story: string;
  }> = [];

  for (const location of DAILY_LOCATIONS) {
    (Object.keys(location.stories) as DailyGame[]).forEach((game) => {
      location.stories[game].forEach((story, index) => {
        stories.push({
          storyId: `${location.id}-${game}-${index + 1}`,
          location,
          game,
          story
        });
      });
    });
  }

  return stories;
}

const ALL_STORIES = flattenStories();

export function getDailyChallenge(dateKey: string, debugOffset = 0): DailyChallenge {
  const random = seededRandom(hashString(`${dateKey}:daily:${debugOffset}`));
  const story = ALL_STORIES[Math.floor(random() * ALL_STORIES.length)];

  const roll = random();
  const difficulty: DailyDifficulty = roll < 0.30
    ? 'easy'
    : roll < 0.80
      ? 'medium'
      : 'hard';

  const settings = DIFFICULTIES[difficulty];
  const key = debugOffset > 0 ? `${dateKey}:test:${debugOffset}` : dateKey;

  return {
    key,
    dateKey,
    storyId: story.storyId,
    game: story.game,
    story: story.story,
    locationId: story.location.id,
    locationTitle: story.location.title,
    image: story.location.image,
    difficulty,
    difficultyLabel: settings.label,
    threshold: settings.thresholds[story.game],
    reward: settings.reward
  };
}

export function formatDailyGoal(challenge: DailyChallenge): string {
  if (challenge.game === 'guess') {
    return `Средняя близость не ниже ${challenge.threshold}%`;
  }
  return `Наберите не меньше ${challenge.threshold} из 10`;
}

export function formatDailyValue(game: DailyGame, value: number): string {
  if (game === 'guess') return `${value}%`;
  return `${value} из 10`;
}

export function createEmptyDailyProgress(key: string): DailyProgress {
  return {
    key,
    completed: false,
    attempts: 0,
    bestValue: 0,
    completedValue: null,
    reward: 0
  };
}

export function loadDailyProgress(key: string): DailyProgress {
  try {
    const raw = localStorage.getItem(DAILY_PROGRESS_KEY);
    if (!raw) return createEmptyDailyProgress(key);

    const parsed = JSON.parse(raw) as Partial<DailyProgress>;
    if (parsed.key !== key) return createEmptyDailyProgress(key);

    return {
      key,
      completed: parsed.completed === true,
      attempts: typeof parsed.attempts === 'number' ? Math.max(0, Math.floor(parsed.attempts)) : 0,
      bestValue: typeof parsed.bestValue === 'number' ? Math.max(0, parsed.bestValue) : 0,
      completedValue: typeof parsed.completedValue === 'number' ? parsed.completedValue : null,
      reward: typeof parsed.reward === 'number' ? Math.max(0, Math.floor(parsed.reward)) : 0
    };
  } catch {
    return createEmptyDailyProgress(key);
  }
}

export function saveDailyProgress(progress: DailyProgress): void {
  try {
    localStorage.setItem(DAILY_PROGRESS_KEY, JSON.stringify(progress));
  } catch {
    // Daily challenge remains playable when storage is unavailable.
  }
}
